export const getFeaturedMovies = () => movies.filter((m) => m.featured);
export const getTrendingMovies = () => movies.filter((m) => m.trending);
export const getNewMovies = () => movies.filter((m) => m.new);
export const getMovieById = (id: number) => movies.find((m) => m.id === id);
export const getMovieBySlug = (slug: string) => movies.find((m) => m.slug === slug);
export const getRelatedMovies = (movie: Movie, limit = 6) =>
  movies
    .filter((m) => m.id !== movie.id && m.genres.some((g) => movie.genres.includes(g)))
    .slice(0, limit);

export const formatViews = (views: number): string => {
  if (views >= 1_000_000) return `${(views / 1_000_000).toFixed(1)}M`;
  if (views >= 1_000) return `${(views / 1_000).toFixed(0)}K`;
  return views.toString();
};
